"""V0.4.40: the post-conversion verification + polish LAYER.

A post-output LLM layer that runs AFTER ``render_summary_markdown``
assembles the final per-chapter output. The generation LLM already did
a 7/10 job; this layer fills holes + fixes mistakes to make it 9/10-10/10.
The LLM is in a VERIFICATION role (not generation) — it spends its full
context + attention on fixing mistakes instead of generating from scratch
(division of labor). Runs every conversion (non-skippable — catches
LLM-variance-driven defects each run).

**Focus** (the 4 concerns that slip past the deterministic in-pipeline
postchecks):
  1. DATES — every ``(Author Year)`` citation's year matches the source.
  2. NAMES — every cited author is a real source author, correctly
     attributed (not fabricated/garbled/misattributed).
  3. CRITICAL OMISSIONS — key source claims/contributors the summary
     missed (the binding-constraint class — the V0.4.37/V0.4.38
     coverage regressions were thorough omissions).
  4. HALLUCINATIONS — fabricated claims not in the source.

**Design** — mirrors the proven D3/garble LLM-repair pattern
(``repair_d3_quotes_via_llm`` / ``repair_garbles_via_llm``):
  - **Targeted corrections, NOT a full rewrite.** The LLM returns a JSON
    array of ``{original, corrected, reason}``; the system applies each
    as a verbatim string replacement (the ``original`` must be an exact
    substring). The LLM can't rewrite the whole summary — only propose
    located fixes. This is the key safety lever (avoids the V0.02
    ``auto_repair`` full-rewrite corruption failure mode).
  - **D3-style guard.** After applying corrections, re-run the
    deterministic postchecks (garbles + stray-quotes) on the polished
    output. Reject (keep the original) if the polished output has MORE
    deterministic flags OR is >15% different in length. Strict-
    improvement.
  - **Fail-open.** If the LLM call fails / returns malformed JSON / no
    corrections apply, the original output is kept unchanged. The
    verification layer NEVER breaks the conversion.
  - **Content-agnostic (Rule 1).** The verification prompt checks
    against the runtime source for ANY book — no hardcoded names/dates/
    concepts. Works on a physics textbook, a novel, or a cooking manual.
  - **Audit trail.** Every applied correction is logged as a
    ``verification`` Issue (severity="fix") in the conversion log; the
    human 4-pillar audit can see exactly what the layer changed.

**V0.5.6 (glossary-driven coverage + loosened quote-guard + final-check)**:
  - The V0.5.5 audit found the verification LAYER correctly flagged 8
    missing source authors (the B1 word-boundary fix worked), but the
    gap-fill only closed 3 of 8 (Croewe+Lowenthal+Munro added; 5 still
    missing). The gap-fill's quote-guard (the V18.20.3.2 parenthetical-
    promotion veto) DROPPED bullets for the 5 missing authors because
    the LLM couldn't find a verbatim source quote (they were "see also"
    citations, not active subjects in the source). The V0.5.6 fix:
    use the LLM-generated source glossary (the ``source_glossary``
    field on ``SummaryResult``, populated by the master-summary call's
    ``<name_glossary>`` block) as the coverage ground truth + loosen
    the quote-guard for glossary-sourced authors (the glossary IS the
    grounding — it was extracted from the source by the LLM).
  - **Coverage ground truth**: if a glossary is available (non-empty
    ``names``), the LAYER uses the glossary's ``names`` list as the
    ground truth (LLM-extracted, catches authors the regex misses).
    Else falls back to ``extract_citations`` (the V0.5.5 behavior).
    The flag logs the cross-reference buckets (confirmed/llm_only/
    regex_only) via ``cross_reference_glossary``.
  - **Loosened D4 guard**: a newly-added author that IS in the
    glossary is NOT flagged/dropped as a hallucination (the glossary
    grounds it). For authors NOT in the glossary, the strict V0.5.4
    D4 guard still fires (prevents fabrication).
  - **Final-check round 4** (in ``gap_fill_batch.batch_gap_fill``):
    after the standard rounds terminate, if glossary-sourced authors
    are still missing, fire a TARGETED round 4 using the glossary
    context as the grounding + the loosened quote-guard.

**V0.5.4 (Track B2+C3+D4+D1+A1 — verification LAYER evolution)**:
  - **A1**: ``_strip_metadata_wrapper`` — strips the run-metadata
    wrapper (``<!-- generated-by -->``, ``---\\n*Generated by ...*``,
    ``<!-- COMPLETE -->``) before the deterministic date-check, so the
    wrapper's run-timestamp dates are no longer FP-flagged as
    hallucinations/omissions (the AUDIT-V0.5.3-ground-truth confirmed
    4 of 5 date flags were wrapper- or range-component FP).
  - **B2**: coverage-targeting prompt is now SPECIFIC — lists EACH
    missing author with their year(s) from the source, so the LLM can
    produce a grounded bullet per author (the previous generic
    "add missing authors" prompt produced 16 generic authors but missed
    the 7 the LAYER flagged).
  - **C3**: prompt now includes an explicit dedup instruction — "before
    adding a bullet for an author, check the existing summary; if the
    author is already cited, do NOT add a duplicate bullet." (The
    AUDIT-V0.5.3 found [a name]/[a name]/[a name] cited twice.)
  - **D4**: gap-fill hallucination guard — after the LLM applies the
    gap-fill corrections, re-run ``extract_citations`` on the polished
    text, diff the post-author set against the pre-author set, and for
    each newly-added author NOT in the source's author set, drop the
    bullet that introduced it + flag a gap-fill hallucination.
  - **D1**: ``_apply_deterministic_fixes`` — rule-based auto-apply for
    deterministic, unambiguous corrections (en-dash → hyphen in year
    ranges). Each auto-applied fix logs a
    ``✨ V0.5.4 auto-apply: [detector] {detail}`` line. Conservative —
    judgment-based fixes (missing-author gap-fill, claim-similarity)
    stay flag-only.

**Architectural rationale** (per the user's direction): adding more
in-pipeline deterministic MODULES is fragile — every book is different,
each module catches some defects but misses others, + the combination is
leaky. This LAYER catches the RESIDUE — whatever mistakes passed the
in-pipeline mistake-proofing — by operating on the FINAL assembled
output with a semantic LLM check the deterministic checks can't do.
"""

