LogCallback = Callable[[str, str], None]

# ─────────────────────────────────────────────────────────────────────────────
# V0.4.40: the verification + polish prompt.
#
# Genre-agnostic (Rule 1): the prompt verifies the summary against the
# runtime source for ANY book. The 4 focus areas (Dates, Names, Omissions,
# Hallucinations) are universal concerns (any discipline's citations have
# years + authors; any summary can omit or fabricate). The prompt asks for
# TARGETED corrections (a JSON array of exact-substring replacements), NOT
# a full rewrite — the system applies each correction verbatim, so the LLM
# can't rewrite the whole summary (avoids the V0.02 auto_repair failure
# mode where a full-rewrite corrupted valid paraphrase words).
# ─────────────────────────────────────────────────────────────────────────────

_VERIFICATION_PROMPT = """You are a verification + polish pass. The SUMMARY below was generated from the SOURCE text. The summary is already a ~7/10 job; your task is to fill holes + fix mistakes to make it 9/10-10/10. Verify the summary against the source for exactly these 4 concerns:

1. DATES: every "(Author Year)" citation — the year must match the source. If a year is wrong, correct it.
2. NAMES: every cited author — the name must be a real source author AND correctly attributed. If a name is wrong/fabricated/misattributed, correct it (or remove the fabricated claim).
3. CRITICAL OMISSIONS: key source claims/contributors the summary missed. Add a concise grounded bullet (or thorough sentence) for each critical omission.
4. HALLUCINATIONS: fabricated claims (claims not in the source). Remove or correct each.

Return a JSON array of TARGETED corrections. Each correction MUST be: {"original": "<an EXACT substring of the summary to replace>", "corrected": "<the replacement text>", "reason": "<one of: date|name|omission|hallucination>"}.

Rules:
- The "original" field MUST be an EXACT substring of the SUMMARY (copied verbatim, including punctuation) so it can be located + replaced. If you can't quote an exact substring, don't propose the correction.
- Do NOT rewrite the whole summary. Only targeted, located corrections.
- For omissions, the "original" can be a short anchor substring where the new bullet/sentence should be INSERTED (the "corrected" is the anchor + the new content).
- Return [] if no corrections are needed.
- Output ONLY the JSON array, no commentary, no markdown fences.

DEVIL'S ADVOCATE — V0.5.4 (Track E4):
- Argue AGAINST the summary. Default to scrutinizing, not approving.
- Find the WEAKEST claim in the summary — the single claim most likely to be a hallucination, misattribution, or unsupported paraphrase.
- For each weak claim: open the SOURCE, search for the supporting evidence, and if you cannot find a verbatim or near-verbatim match, flag it as a hallucination/misattribution (use the "original"/"corrected"/"reason" JSON shape above).
- Pay extra scrutiny to: numeric facts (years, counts, percentages), direct quotes (must match the source verbatim), and attributions ("Author X said Y" — verify Author X actually said Y in the source).
- Only if you have scrutinized the summary rigorously AND genuinely cannot find any weakness, return []. A rubber-stamp [] without scrutiny is a failure mode — the verification LAYER's value depends on adversarial review.

SOURCE TEXT (for verification):
{source}

SUMMARY TO VERIFY:
"""


def _extract_corrections(raw: str) -> list[dict]:
    """Extract the JSON array of corrections from the LLM response.

    Fail-open: returns [] if no valid JSON array is found. Handles
    ```json fences + surrounding commentary.
    """
    if not raw:
        return []
    text = raw.strip()
    # Strip ```json ... ``` fences if present.
    fence = re.search(r"```(?:json)?\s*(.*?)\s*```", text, re.DOTALL)
    if fence:
        text = fence.group(1).strip()
    # Find the first [...] block.
    m = re.search(r"\[\s*\{.*?\}\s*\]", text, re.DOTALL)
    if not m:
        # Maybe an empty array "[]".
        if re.search(r"\[\s*\]", text):
            return []
        return []
    try:
        parsed = json.loads(m.group(0))
    except json.JSONDecodeError:
        return []
    if not isinstance(parsed, list):
        return []
    return [c for c in parsed if isinstance(c, dict)]


def _count_polish_guard_flags(text: str, source_text: str, field_label: str) -> int:
    """Count the deterministic postcheck flags (garbles + stray-quotes) on a
    text. Used by the D3-style guard to verify the polished output doesn't
    introduce new structural defects.
    """
    if not text:
        return 0
    try:
        from core.summarisation.postchecks.garble.dropped_letter import (
            detect_dropped_letter_garble,
        )
        from core.summarisation.postchecks.garble.quote_repair import (
            repair_stray_quotes_v2,
        )
        from core.summarisation.postchecks.garble.token_detectors import (
            detect_word_fragment_merge,
        )

        source_words = set(re.findall(r"\b[a-z]+\b", (source_text or "").lower()))
        _, sq = repair_stray_quotes_v2(text, field_label)
        _, frag = detect_word_fragment_merge(
            text, field_label, source_text or "", source_words=source_words
        )
        _, dropped = detect_dropped_letter_garble(
            text, field_label, source_text or "", source_words=source_words, auto_repair=False
        )
        return len(sq or []) + len(frag or []) + len(dropped or [])
    except Exception:
        logger.warning("polish-guard flag count crashed (non-fatal); returning 0")
        return 0


# ─────────────────────────────────────────────────────────────────────────────
# V0.5.4 (A1): metadata-wrapper strip helper.
#
# The rendered per-chapter summary carries provenance metadata:
#   - an HTML comment ``<!-- generated-by: ... | started=YYYY-MM-DDTHH:MM:SS ... -->``
#     (invisible in rendered markdown, but parsed by ``extract_dates``
#     as a run timestamp).
#   - a visible footer block
#     ``\\n---\\n\\n*Generated by Elixir v... · run ... · YYYY-MM-DDTHH:MM:SS · N bullets*\\n``
#     (the human-readable stamp).
#   - the COMPLETE sentinel ``<!-- COMPLETE run_id=... -->`` at the end.
#   - (book-level summaries additionally carry a ``> Provider: ... | YYYY-MM-DD``
#     blockquote — included for safety when this helper is reused).
#
# All of these carry RUN dates (the timestamp the summary was generated)
# — NOT source dates. Passing the wrapper to ``extract_dates`` produces
# false-positive "hallucination" + "omission" flags (the
# AUDIT-V0.5.3-ground-truth confirmed 4 of 5 date flags were wrapper- or
# range-component FP).
#
# This helper returns ONLY the summary BODY — the wrapper lines are
# removed. The full ``rendered_md`` is still used for the LLM
# verification + the final output; the stripped body is used ONLY for
# the date-check (where wrapper dates would otherwise cause FP).
# ─────────────────────────────────────────────────────────────────────────────


def _strip_metadata_wrapper(rendered_md: str) -> str:
    """A1 (V0.5.4): strip run-metadata wrapper lines from a rendered
    summary markdown before the deterministic date-check.

    Returns ONLY the summary BODY (the wrapper provenance lines removed).
    Does NOT modify the caller's ``rendered_md`` (returns a new string).
    Fail-open: on any unexpected shape, returns the input unchanged
    (the date-check is advisory-only — never breaks the conversion).
    """
    if not rendered_md:
        return rendered_md
    body = rendered_md
    # Strip the visible footer block: a horizontal rule followed by an
    # italic ``*Generated by Elixir v... · run ... · YYYY-MM-DDTHH:MM:SS · N bullets*``
    # + surrounding blank lines. The rule + italic form is the unique
    # provenance-footer shape; it does not appear in summary bodies.
    body = re.sub(
        r"\n*---\n+\*Generated by[^\n]*\*\s*\n*",
        "\n",
        body,
    )
    # Strip the COMPLETE sentinel (run-id-stamped or legacy bare form).
    body = re.sub(r"\n*<!--\s*COMPLETE[^\n]*-->\s*\n*", "\n", body)
    # Strip the generated-by provenance HTML comment + the trailing
    # blank line that follows it (so the title flows directly into the
    # body's first section).
    body = re.sub(r"<!--\s*generated-by[^\n]*-->\s*\n?", "", body)
    # Strip book-summary "Provider: ... | YYYY-MM-DD" blockquote lines
    # (present only in the assembled book summary; the per-chapter
    # summary never carries this — but this is a content-agnostic
    # helper, so it strips the pattern whenever present).
    body = re.sub(r"^\s*>\s+Provider:[^\n]*\n", "", body, flags=re.MULTILINE)
    return body


# ─────────────────────────────────────────────────────────────────────────────
# V0.5.4 (D1): deterministic auto-apply helpers.
#
# Currently the LAYER only LOGS issues (severity="flag") — the actual
# fix relies on the LLM's targeted-correction response (severity="fix").
# These helpers add rule-based auto-apply for issues where the fix is
# deterministic + unambiguous (no LLM judgment involved).
#
# CONSERVATIVE by design — judgment-based fixes (missing-author gap-fill,
# claim-similarity, semantic omissions) stay flag-only; the LLM handles
# those via targeted corrections.
# ─────────────────────────────────────────────────────────────────────────────


# V0.5.4 (D1 / TRACK-A A3): en-dash (U+2013) in a 4-digit year range
# (e.g. "1887–1902"). The date_extractor's regex class now accepts en-
# dash (TRACK-A fix), so this normalization is for the OUTPUT text —
# making the human-readable summary use the standard ASCII hyphen form
# for year ranges (the canonical form for comparison + style guides).
_EN_DASH_YEAR_RANGE = re.compile(r"(\d{4})\u2013(\d{4})")


def _apply_deterministic_fixes(text: str, issues: list[Issue]) -> str:
    """D1 (V0.5.4): apply deterministic, unambiguous corrections to the
    polished summary text. Adds ``verification_auto_apply_*`` Issue
    entries (severity="fix") for each applied correction so the audit
    trail records what the LAYER changed beyond the LLM's targeted
    corrections.

    Currently applies:
      - en-dash normalization (TRACK-A A3): replace U+2013 (en-dash)
        with U+002D (hyphen) in year ranges (``"1887–1902"`` →
        ``"1887-1902"``) so the date-check's normalized form matches
        the source's hyphen form on subsequent runs + the rendered
        markdown uses the canonical ASCII form.

    Conservative: judgment-based fixes (missing-author gap-fill,
    claim-similarity, semantic omissions) stay flag-only — the LLM
    handles those via targeted corrections.
    """
    if not text:
        return text
    fixed = text

    # En-dash normalization in year ranges.
    _n_ed = [0]

    def _ed_repl(m: re.Match) -> str:
        _n_ed[0] += 1
        return f"{m.group(1)}-{m.group(2)}"

    fixed = _EN_DASH_YEAR_RANGE.sub(_ed_repl, fixed)
    if _n_ed[0] > 0:
        issues.append(
            Issue(
                detector="verification_auto_apply_en_dash",
                severity="fix",
                field="summary",
                snippet=f"{_n_ed[0]} en-dash range(s)",
                detail=(
                    f"en-dash normalization: replaced {_n_ed[0]} U+2013 en-dash(es) "
                    f"in year-range(s) with U+002D hyphen (the canonical ASCII "
                    f"form; matches the date-check's normalized source form)."
                ),
            )
        )

    return fixed


def verify_and_polish_summary(
    rendered_md: str,
    source_text: str,
    settings=None,
    log: LogCallback | None = None,
) -> tuple[str, list[Issue]]:
    """V0.4.40: the post-conversion verification + polish LAYER.

    Sends the rendered per-chapter summary + a clamped (≤50k-char) source
    excerpt to the LLM with the verification prompt. The LLM returns
    TARGETED corrections (a JSON array of ``{original, corrected, reason}``);
    the system applies each as a verbatim string replacement. D3-style
    guard: reject (keep the original) if the polished output has MORE
    deterministic flags OR is >15% different in length. Fail-open.

    V0.5.4 evolution:
      - A1: the date-check runs on the wrapper-stripped body (no FP on
        run-metadata dates).
      - B2+C3: the coverage-targeting prompt is now specific (names each
        missing author + their year) + includes a dedup instruction.
      - D4: a gap-fill hallucination guard runs AFTER the LLM corrections
        are applied — newly-added authors not in the source's author set
        are dropped + flagged.
      - D1: ``_apply_deterministic_fixes`` runs at every return path —
        en-dash normalization is applied even when the LLM is unavailable.

    Args:
        rendered_md: the rendered per-chapter summary markdown (the output
            of ``render_summary_markdown``).
        source_text: the chapter source text (for verification + the guard).
        settings: optional Settings; built from ``utils.settings.Settings``
            when None.
        log: optional log callback.

    Returns:
        ``(polished_md, issues)``. Each issue is a ``verification`` fix
        (a correction applied) or flag (the layer kept the original).
    """
    issues: list[Issue] = []
    if not rendered_md or not source_text:
        # Even on the empty-input path, apply deterministic fixes (no-op
        # when the input is empty — keeps the contract that the returned
        # text always goes through canonicalization).
        return _apply_deterministic_fixes(rendered_md, issues), issues

    # V0.5.4 (A1): strip the run-metadata wrapper BEFORE the date-check.
    # The wrapper's ``<!-- generated-by ... started=YYYY-MM-DDTHH:MM:SS -->``
    # + ``*Generated by ... · YYYY-MM-DDTHH:MM:SS · ...*`` footer carry
    # RUN dates (the timestamp the summary was generated), NOT source
    # dates. Passing them to ``extract_dates`` produces FP "hallucination"
    # + "omission" flags (the AUDIT-V0.5.3-ground-truth confirmed 4 of 5
    # date flags were wrapper- or range-component FP). The stripped body
    # is used ONLY for the date-check; the LLM verification + the final
    # output still use the full ``rendered_md``.
    _body_for_date_check = _strip_metadata_wrapper(rendered_md)

    # V0.5.0: deterministic date-check (runs BEFORE the LLM call —
    # flags date mismatches the LLM might miss). Extract all dates from
    # the summary + source, compare (hallucinated/omitted). Advisory
    # flags (severity="flag") — the LLM corrections (severity="fix")
    # handle the actual fixing. Content-agnostic (Rule 1 — generic date
    # structure patterns, no hardcoded dates).
    try:
        from core.preprocessing.date_extractor import compare_dates, extract_dates

        _summ_dates = extract_dates(_body_for_date_check)
        _src_dates = extract_dates(source_text)
        _date_cmp = compare_dates(_summ_dates, _src_dates)
        if _date_cmp["hallucinated_count"] > 0:
            for _hd in _date_cmp["hallucinated"][:10]:
                issues.append(
                    Issue(
                        detector="verification_date_check",
                        severity="flag",
                        field="summary",
                        snippet=_hd.text[:60],
                        detail=(
                            f"deterministic date-check: summary date {_hd.text!r} "
                            f"({_hd.normalized}) NOT found in source — possible fabrication."
                        ),
                    )
                )
        if _date_cmp["omitted_count"] > 0:
            for _od in _date_cmp["omitted"][:10]:
                issues.append(
                    Issue(
                        detector="verification_date_check",
                        severity="flag",
                        field="summary",
                        snippet=_od.text[:60],
                        detail=(
                            f"deterministic date-check: source date {_od.text!r} "
                            f"({_od.normalized}) NOT found in summary — possible omission."
                        ),
                    )
                )
    except Exception:
        logger.warning("deterministic date-check crashed (non-fatal)")

    if settings is None:
        from utils.settings import Settings as _S

        settings = _S()

    model = settings.get("summarisation.model", "") or settings.get(
        "summarisation.primary_model", ""
    )
    if not model:
        # No model configured → no LLM call, but the deterministic
        # auto-apply (en-dash normalization) still runs.
        return _apply_deterministic_fixes(rendered_md, issues), issues  # no-op (fail-open)

    try:
        # V0.4.13 pattern: use the provider abstraction (Ollama + llama.cpp).
        from core.llm.llm_provider_impl import create_provider

        arch = settings.get("summarisation.model_architecture", "single_local") or "single_local"
        if arch == "llamacpp":
            provider_name = "llamacpp"
        elif arch in ("single_api", "dual_api"):
            provider_name = settings.get("summarisation.cloud_provider", "openai_compatible")
        else:
            provider_name = "ollama"

        if provider_name not in ("ollama", "llamacpp"):
            return _apply_deterministic_fixes(
                rendered_md, issues
            ), issues  # cloud providers not supported

        provider = create_provider(provider_name, settings)
        if not provider:
            return _apply_deterministic_fixes(rendered_md, issues), issues

        # V0.5.1 / V0.5.4 (B2+C3): coverage-targeting — extract source
        # authors + their year(s), check which authors are NOT covered
        # in the summary, add a SPECIFIC list (author + year) to the LLM
        # prompt so the verification LLM can ADD grounded bullets per
        # missing author (the "10/10 coverage" objective). The prompt
        # also includes an explicit dedup instruction (C3) so the LLM
        # does not re-cite authors already covered.
        #
        # Content-agnostic (Rule 1 — uses the runtime extract_citations
        # on the source, no hardcoded names).
        _coverage_note = ""
        _src_authors: list[str] = []
        try:
            from core.preprocessing.deterministic_analyzer import extract_citations

            _src_cits = extract_citations(source_text)
            # Build the author → years map (only plausible authors len>=3).
            _src_author_years: dict[str, list[str]] = {}
            for _c in _src_cits:
                _a = _c.get("author") or ""
                if len(_a) < 3:
                    continue
                _yrs = _c.get("years") or ""
                if _a not in _src_author_years:
                    _src_author_years[_a] = []
                for _y in re.split(r"[,\s]+", _yrs):
                    _y = _y.strip()
                    if _y and _y not in _src_author_years[_a]:
                        _src_author_years[_a].append(_y)
            _src_authors = list(_src_author_years.keys())
            _rendered_lower = rendered_md.lower()
            # V0.5.4 (B1): word-boundary regex instead of substring `in`.
            # Pre-V0.5.4 the check was `_a.lower() not in _rendered_lower` —
            # a SUBSTRING test. The AUDIT-V0.5.3-ground-truth found that a
            # 3-letter source author cited once in a subsection was SILENTLY
            # SKIPPED by the coverage check whenever the summary happened to
            # mention a DIFFERENT real source author whose surname CONTAINED
            # that 3-letter substring (e.g. summary "Xyzabc" contains the
            # substring "abc" → false "covered" verdict → no missing-author
            # flag fired for the 3-letter author). Word-boundary anchoring
            # requires the author to appear as a standalone token (anchored
            # by ``\b``) to count as covered, eliminating the
            # false-negative. Content-agnostic (Rule 1 ✓): the regex is built
            # from the runtime extract_citations list, no hardcoded names —
            # the ``\b`` anchors are generic regex, not book-specific.
            _missing = []
            for _a in _src_authors:
                _a_lower = _a.lower()
                _a_plural = _a_lower.rstrip("s")  # crude plural-strip heuristic
                _a_pat = re.compile(r"\b" + re.escape(_a_lower) + r"\b")
                if _a_pat.search(_rendered_lower):
                    continue
                if _a_plural != _a_lower:
                    _a_plural_pat = re.compile(r"\b" + re.escape(_a_plural) + r"\b")
                    if _a_plural_pat.search(_rendered_lower):
                        continue
                _missing.append(_a)
            if _missing:
                # V0.5.4 (B2): list EACH missing author with their year(s)
                # so the LLM can produce a grounded bullet per author
                # (not the previous generic "add missing authors" prompt
                # which the AUDIT-V0.5.3-ground-truth found produced 16
                # authors but missed the 7 the LAYER flagged).
                _missing_author_years: list[str] = []
                for _a in sorted(_missing)[:25]:
                    _yrs = _src_author_years.get(_a, [])
                    if _yrs:
                        if len(_yrs) == 1:
                            _missing_author_years.append(f"{_a} {_yrs[0]}")
                        else:
                            _missing_author_years.append(f"{_a} ({'/'.join(_yrs)})")
                    else:
                        _missing_author_years.append(_a)
                _missing_with_years = "; ".join(_missing_author_years)
                _missing_list = ", ".join(sorted(_missing)[:25])
                _coverage_note = (
                    f"\n\nADDITIONAL COVERAGE CHECK: The following source "
                    f"authors/contributors are NOT in the summary: "
                    f"[{_missing_with_years}]. For EACH author above, add a "
                    f"grounded bullet citing the author + their year + their "
                    f"specific contribution from the source text. "
                    # V0.5.4 (C3): explicit dedup instruction — the
                    # AUDIT-V0.5.3 found authors cited twice (the gap-fill
                    # re-cited authors already covered).
                    f"Before adding a bullet for an author, check the existing "
                    f"summary — if the author is already cited, do NOT add a "
                    f"duplicate bullet. Do NOT re-cite authors already covered. "
                    f'Use the targeted-correction format: the "original" is '
                    f"the anchor text (e.g. the **Conclusions** bullet) and the "
                    f'"corrected" is the anchor + the new bullet(s) inserted '
                    f"before it."
                )
                issues.append(
                    Issue(
                        detector="verification_coverage",
                        severity="flag",
                        field="summary",
                        snippet=f"missing {len(_missing)} author(s)",
                        detail=(
                            f"coverage-targeting: {len(_missing)} source author(s) "
                            f"NOT found in the summary ({_missing_list[:100]}). "
                            f"Added to the LLM verification prompt."
                        ),
                    )
                )
        except Exception:
            logger.warning("coverage-targeting extract crashed (non-fatal)")

        # The verification needs the full source (to check omissions +
        # hallucinations), not just a 20k excerpt like the garble repair.
        # Clamp to 50k chars (~10k tokens) for very long chapters.
        # NOTE: use .replace (not .format) — the prompt contains literal
        # JSON-brace examples {"original": ...} that .format would try to
        # interpret as format fields (KeyError).
        source_excerpt = (source_text or "")[:50000]
        prompt = (
            _VERIFICATION_PROMPT.replace("{source}", source_excerpt) + rendered_md + _coverage_note
        )
        raw = provider.complete(
            prompt=prompt,
            temperature=0.0,
            max_tokens=8192,
            model=model,
        )

        if not raw or len(raw) < 10:
            return _apply_deterministic_fixes(
                rendered_md, issues
            ), issues  # empty/short response → no-op

        corrections = _extract_corrections(raw)
        if not corrections:
            return _apply_deterministic_fixes(
                rendered_md, issues
            ), issues  # no corrections proposed → no-op

        # Apply targeted corrections (verbatim string replacements).
        polished = rendered_md
        applied = 0
        skipped = 0
        for c in corrections:
            orig = str(c.get("original", ""))
            corr = str(c.get("corrected", ""))
            reason = str(c.get("reason", "unknown"))
            if not orig or orig == corr:
                continue
            if orig in polished:
                polished = polished.replace(orig, corr, 1)
                applied += 1
                issues.append(
                    Issue(
                        detector="verification",
                        severity="fix",
                        field="summary",
                        snippet=orig[:60],
                        detail=(f"applied {reason} correction: {orig[:50]!r} -> {corr[:50]!r}"),
                    )
                )
            else:
                # The LLM's "original" wasn't an exact substring — skip.
                skipped += 1
        if applied == 0:
            if skipped:
                issues.append(
                    Issue(
                        detector="verification",
                        severity="flag",
                        field="summary",
                        snippet=rendered_md[:60],
                        detail=(
                            f"verification proposed {skipped} correction(s) but "
                            f"none matched an exact substring — original kept."
                        ),
                    )
                )
            return _apply_deterministic_fixes(rendered_md, issues), issues

        # V0.5.4 (D4): gap-fill hallucination guard — after the LLM's
        # targeted corrections are applied, re-run extract_citations on
        # the polished text, diff the post-author set against the pre-
        # author set, and for each newly-added author NOT in the source's
        # author set, drop the bullet that introduced it + flag a gap-fill
        # hallucination. This prevents the coverage-targeting from
        # introducing hallucinations while fixing coverage (the AUDIT-V0.5.3
        # concern that the gap-fill might ADD authors not in the source).
        # Runs BEFORE the length/flag-count guards so those operate on
        # the de-contaminated polished text.
        try:
            from core.preprocessing.deterministic_analyzer import (
                extract_citations as _ec_for_guard,
            )

            _pre_authors = {
                _c.get("author", "") for _c in _ec_for_guard(rendered_md) if _c.get("author")
            }
            _post_cits = _ec_for_guard(polished)
            _post_authors = {_c.get("author", "") for _c in _post_cits if _c.get("author")}
            _src_lower = {_a.lower() for _a in _src_authors if _a}
            _new_authors = _post_authors - _pre_authors
            _fabricated = [
                _a for _a in _new_authors if _a and len(_a) >= 3 and _a.lower() not in _src_lower
            ]
            for _fab in _fabricated:
                # Drop the bullet line(s) containing the fabricated
                # author. The bullet pattern matches a markdown list
                # item ("- ...") that contains the author name on the
                # same line.
                _bullet_pat = re.compile(
                    r"^[ \t]*-[ \t][^\n]*" + re.escape(_fab) + r"[^\n]*\n?",
                    re.MULTILINE,
                )
                polished, _n_dropped = _bullet_pat.subn("", polished)
                issues.append(
                    Issue(
                        detector="verification_gap_fill_hallucination_guard",
                        severity="flag",
                        field="summary",
                        snippet=_fab[:60],
                        detail=(
                            f"gap-fill hallucination guard: author {_fab!r} was "
                            f"introduced by the gap-fill but is NOT in the source's "
                            f"author set — dropped {_n_dropped} bullet(s) containing it."
                        ),
                    )
                )
                if log:
                    log(
                        f"    ✨ V0.5.4 auto-apply: [gap-fill-hallucination-guard] "
                        f"dropped author {_fab!r} (not in source author set).",
                        "INFO",
                    )
        except Exception:
            logger.warning("gap-fill hallucination guard crashed (non-fatal)")

        # D3-style guard: length check (no major rewrite).
        orig_len = len(rendered_md)
        polish_len = len(polished)
        if not (0.85 * orig_len <= polish_len <= 1.15 * orig_len):
            issues.append(
                Issue(
                    detector="verification",
                    severity="flag",
                    field="summary",
                    snippet=rendered_md[:60],
                    detail=(
                        f"verification rejected: polished length {polish_len} outside "
                        f"85-115% of original {orig_len} — original kept."
                    ),
                )
            )
            return _apply_deterministic_fixes(rendered_md, issues), issues

        # D3-style guard: flag-count check (no new structural defects).
        pre_flags = _count_polish_guard_flags(rendered_md, source_text, "summary")
        post_flags = _count_polish_guard_flags(polished, source_text, "summary")
        if post_flags > pre_flags:
            issues.append(
                Issue(
                    detector="verification",
                    severity="flag",
                    field="summary",
                    snippet=rendered_md[:60],
                    detail=(
                        f"verification rejected: polished output has {post_flags} "
                        f"deterministic flags (was {pre_flags}) — correction introduced "
                        f"new structural defects; original kept."
                    ),
                )
            )
            return _apply_deterministic_fixes(rendered_md, issues), issues

        if log:
            log(
                f"    ✨ V0.4.40 verification: applied {applied} targeted correction(s) "
                f"({skipped} skipped) — polished output "
                f"({polish_len} chars, {post_flags} flags vs {pre_flags}).",
                "INFO",
            )
        return _apply_deterministic_fixes(polished, issues), issues
    except Exception as e:
        logger.warning("verification phase crashed (non-fatal): %s: %s", type(e).__name__, e)
        issues.append(
            Issue(
                detector="verification",
                severity="flag",
                field="summary",
                snippet=rendered_md[:60],
                detail=f"verification phase failed: {type(e).__name__}: {e} — original kept.",
            )
        )
        return _apply_deterministic_fixes(rendered_md, issues), issues
