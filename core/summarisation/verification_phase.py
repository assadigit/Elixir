# V0.5.6: source-glossary side-channel + cross-reference helper.
#
# The V0.5.6 architecture (per the user's directive) fuses a
# ``<name_glossary>`` block into the master-summary LLM call. The
# glossary is persisted to ``summaries/.glossaries/<chapter>.glossary.md``
# + exposed via a ``source_glossary`` field on ``SummaryResult`` (added
# by the V056-PROMPT-PARSER subagent). The verification LAYER consumes
# the glossary as the coverage ground truth + the loosened quote-guard
# membership test.
#
# To avoid an invasive signature change for callers that don't have a
# ``SummaryResult`` in scope (the ``ChapterCheckpointSaver`` path passes
# the rendered markdown + source text, not the SummaryResult), the
# glossary is stashed in a module-level cache keyed by chapter heading
# (set by the master-summary wiring before the LAYER runs) + looked up
# by the LAYER when the keyword ``source_glossary`` argument is None.
#
# Content-agnostic (Rule 1): the cache stores whatever the runtime
# master-summary call extracted — no hardcoded names. The
# ``cross_reference_glossary`` helper buckets the LLM-extracted names
# vs the regex-extracted names (confirmed / llm_only / regex_only) for
# the audit-trail log line.
# ─────────────────────────────────────────────────────────────────────────────

# Module-level side-channel: heading → glossary dict. Populated by
# ``set_chapter_glossary`` (the master-summary wiring calls this after
# the ``<name_glossary>`` block is parsed); read by
# ``get_chapter_glossary`` (the LAYER picks this up when the
# ``source_glossary`` keyword arg is None — fail-open to the V0.5.5
# regex behavior when the glossary isn't available).
_glossary_cache: dict[str, dict] = {}


def set_chapter_glossary(heading: str, glossary: dict | None) -> None:
    """V0.5.6: stash the LLM-generated source glossary for a chapter
    heading in the module-level side-channel. Called by the master-
    summary wiring (the V056-PROMPT-PARSER subagent) after the
    ``<name_glossary>`` block is parsed. None/empty → the entry is
    removed (fail-open to the V0.5.5 regex behavior).
    """
    if not heading:
        return
    if not glossary:
        _glossary_cache.pop(heading, None)
        return
    _glossary_cache[heading] = glossary


def get_chapter_glossary(heading: str | None) -> dict | None:
    """V0.5.6: fetch the stashed glossary for a chapter heading (or
    None when no glossary was stashed / the heading is empty)."""
    if not heading:
        return None
    return _glossary_cache.get(heading)


def clear_glossary_cache() -> None:
    """V0.5.6: clear the module-level glossary cache (used by tests
    to isolate test cases from each other)."""
    _glossary_cache.clear()


def _extract_glossary_names(glossary: dict | list | None) -> list[str]:
    """V0.5.6: defensive extractor for the glossary's ``names`` section.

    The V056-PROMPT-PARSER subagent's exact glossary shape is not
    finalized at this writing — supported shapes (fail-open across
    all of them):
      - ``{"names": [{"name": "Bak", "year": "1946", ...}, ...]}`` —
        the documented shape (list of name dicts with a ``name`` key).
      - ``{"names": ["Bak", "Jack", ...]}`` — a plain list of strings.
      - ``[{"name": "Bak", ...}, ...]`` — the glossary itself is the
        names list (no ``names`` wrapper key).
      - ``["Bak", "Jack", ...]`` — a plain list of strings (legacy
        caller-stash form).
    Returns a de-duplicated list of names (length >= 3, no empties).
    """
    if not glossary:
        return []
    names_raw: object
    if isinstance(glossary, dict):
        names_raw = glossary.get("names") or glossary.get("authors") or []
    else:
        names_raw = glossary
    if not isinstance(names_raw, list):
        return []
    out: list[str] = []
    seen: set[str] = set()
    for entry in names_raw:
        name = ""
        if isinstance(entry, str):
            name = entry
        elif isinstance(entry, dict):
            name = str(entry.get("name") or entry.get("author") or entry.get("surname") or "")
        name = name.strip()
        if len(name) < 3 or name.lower() in seen:
            continue
        seen.add(name.lower())
        out.append(name)
    return out


def _extract_glossary_path(glossary: dict | None) -> str:
    """V0.5.6: defensive extractor for the glossary's persisted file
    path (for the audit-trail log line). Returns "(none)" when the
    path is absent / the glossary is not a dict."""
    if isinstance(glossary, dict):
        p = glossary.get("path") or glossary.get("file") or glossary.get("glossary_path")
        if p:
            return str(p)
    return "(none)"


def _extract_glossary_context_for(glossary: dict | list | None, name: str) -> str:
    """V0.5.6: defensive extractor for a single author's glossary
    context line (e.g. "Bak (1946) — coined the 'higher level'
    character organization concept"). Returns "" when no context is
    available for the name.

    Used by:
      - the coverage-targeting prompt (so the LLM gets the glossary
        context per missing author — the grounding).
      - the final-check round 4 prompt in ``gap_fill_batch`` (same).
    """
    if not glossary or not name:
        return ""
    entries: list
    if isinstance(glossary, dict):
        names_section = glossary.get("names") or glossary.get("authors") or []
        entries = names_section if isinstance(names_section, list) else []
    elif isinstance(glossary, list):
        entries = glossary
    else:
        return ""
    name_lower = name.lower()
    for entry in entries:
        if isinstance(entry, str):
            if entry.lower() == name_lower:
                return name  # bare name — no extra context
            continue
        if isinstance(entry, dict):
            entry_name = str(entry.get("name") or entry.get("author") or entry.get("surname") or "")
            if entry_name.lower() == name_lower:
                year = entry.get("year") or entry.get("years") or ""
                context = entry.get("context") or entry.get("description") or ""
                # Build the glossary context line: "Bak (1946) — context"
                # or "Bak — context" when the year is missing.
                if year and context:
                    return f"{entry_name} ({year}) — {context}"
                if year:
                    return f"{entry_name} ({year})"
                if context:
                    return f"{entry_name} — {context}"
                return entry_name
    return ""


def cross_reference_glossary(
    glossary: dict | list | None,
    regex_authors: list[str] | set[str] | None,
) -> dict[str, list[str]]:
    """V0.5.6: bucket the LLM-extracted (glossary) author set vs the
    regex-extracted (``extract_citations``) author set.

    Returns ``{"confirmed": [...], "llm_only": [...], "regex_only":
    [...]}`` where:
      - ``confirmed``: in BOTH the glossary and the regex set (high
        confidence — both methods agree the author is a real source
        author).
      - ``llm_only``: in the glossary but NOT in the regex set (the
        LLM caught an author the regex missed — the V0.5.5 coverage
        gap the glossary closes).
      - ``regex_only``: in the regex set but NOT in the glossary (the
        regex caught an author the LLM missed — usually a
        marginal/duplicate citation the LLM filtered out).

    Used by the coverage flag's audit-trail log line so the human
    audit can see the cross-reference buckets.
    """
    glossary_names = _extract_glossary_names(glossary)
    regex_set = {a.lower() for a in (regex_authors or []) if a and len(a) >= 3}
    glossary_set = {a.lower() for a in glossary_names}
    confirmed_lower = glossary_set & regex_set
    llm_only_lower = glossary_set - regex_set
    regex_only_lower = regex_set - glossary_set
    # Preserve the original-case name (first occurrence wins).
    name_lookup: dict[str, str] = {}
    for a in glossary_names:
        name_lookup.setdefault(a.lower(), a)
    for a in regex_authors or []:
        if a and len(a) >= 3:
            name_lookup.setdefault(a.lower(), a)
    return {
        "confirmed": sorted(name_lookup[k] for k in confirmed_lower),
        "llm_only": sorted(name_lookup[k] for k in llm_only_lower),
        "regex_only": sorted(name_lookup[k] for k in regex_only_lower),
    }


# ─────────────────────────────────────────────────────────────────────────────
# V0.4.40: the verification + polish prompt.
#
# Genre-agnostic (Rule 1): the prompt verifies the summary against the
# runtime source for ANY book. The 4 focus areas (Dates, Names, Omissions,
# Hallucinations) are universal concerns (any discipline's citations have
# years + authors; any summary can omit or fabricate). The prompt asks for
# TARGETED corrections (a JSON array of exact-substring replacements), NOT
# a full rewrite — the system applies each correction verbatim, so the LLM
# can't rewrite the whole summary (avoids the V0.02 auto_repair failure
# mode where a full-rewrite corrupted valid paraphrase words).
# ─────────────────────────────────────────────────────────────────────────────

_VERIFICATION_PROMPT = """You are a verification + polish pass. The SUMMARY below was generated from the SOURCE text. The summary is already a ~7/10 job; your task is to fill holes + fix mistakes to make it 9/10-10/10. Verify the summary against the source for exactly these 4 concerns:

1. DATES: every "(Author Year)" citation — the year must match the source. If a year is wrong, correct it.
2. NAMES: every cited author — the name must be a real source author AND correctly attributed. If a name is wrong/fabricated/misattributed, correct it (or remove the fabricated claim).
3. CRITICAL OMISSIONS: key source claims/contributors the summary missed. Add a concise grounded bullet (or thorough sentence) for each critical omission.
4. HALLUCINATIONS: fabricated claims (claims not in the source). Remove or correct each.

Return a JSON array of TARGETED corrections. Each correction MUST be: {"original": "<an EXACT substring of the summary to replace>", "corrected": "<the replacement text>", "reason": "<one of: date|name|omission|hallucination>"}.

Rules:
- The "original" field MUST be an EXACT substring of the SUMMARY (copied verbatim, including punctuation) so it can be located + replaced. If you can't quote an exact substring, don't propose the correction.
- Do NOT rewrite the whole summary. Only targeted, located corrections.
- For omissions, the "original" can be a short anchor substring where the new bullet/sentence should be INSERTED (the "corrected" is the anchor + the new content).
- Return [] if no corrections are needed.
- Output ONLY the JSON array, no commentary, no markdown fences.

DEVIL'S ADVOCATE — V0.5.4 (Track E4):
- Argue AGAINST the summary. Default to scrutinizing, not approving.
- Find the WEAKEST claim in the summary — the single claim most likely to be a hallucination, misattribution, or unsupported paraphrase.
- For each weak claim: open the SOURCE, search for the supporting evidence, and if you cannot find a verbatim or near-verbatim match, flag it as a hallucination/misattribution (use the "original"/"corrected"/"reason" JSON shape above).
- Pay extra scrutiny to: numeric facts (years, counts, percentages), direct quotes (must match the source verbatim), and attributions ("Author X said Y" — verify Author X actually said Y in the source).
- Only if you have scrutinized the summary rigorously AND genuinely cannot find any weakness, return []. A rubber-stamp [] without scrutiny is a failure mode — the verification LAYER's value depends on adversarial review.

SOURCE TEXT (for verification):
{source}

SUMMARY TO VERIFY:
"""


def _extract_corrections(raw: str) -> list[dict]:
    """Extract the JSON array of corrections from the LLM response.

    Fail-open: returns [] if no valid JSON array is found. Handles
    ```json fences + surrounding commentary.
    """
    if not raw:
        return []
    text = raw.strip()
    # Strip ```json ... ``` fences if present.
    fence = re.search(r"```(?:json)?\s*(.*?)\s*```", text, re.DOTALL)
    if fence:
        text = fence.group(1).strip()
    # Find the first [...] block.
    m = re.search(r"\[\s*\{.*?\}\s*\]", text, re.DOTALL)
    if not m:
        # Maybe an empty array "[]".
        if re.search(r"\[\s*\]", text):
            return []
        return []
    try:
        parsed = json.loads(m.group(0))
    except json.JSONDecodeError:
        return []
    if not isinstance(parsed, list):
        return []
    return [c for c in parsed if isinstance(c, dict)]


def _count_polish_guard_flags(text: str, source_text: str, field_label: str) -> int:
    """Count the deterministic postcheck flags (garbles + stray-quotes) on a
    text. Used by the D3-style guard to verify the polished output doesn't
    introduce new structural defects.
    """
    if not text:
        return 0
    try:
        from core.summarisation.postchecks.garble.dropped_letter import (
            detect_dropped_letter_garble,
        )
        from core.summarisation.postchecks.garble.quote_repair import (
            repair_stray_quotes_v2,
        )
        from core.summarisation.postchecks.garble.token_detectors import (
            detect_word_fragment_merge,
        )

        source_words = set(re.findall(r"\b[a-z]+\b", (source_text or "").lower()))
        _, sq = repair_stray_quotes_v2(text, field_label)
        _, frag = detect_word_fragment_merge(
            text, field_label, source_text or "", source_words=source_words
        )
        _, dropped = detect_dropped_letter_garble(
            text, field_label, source_text or "", source_words=source_words, auto_repair=False
        )
        return len(sq or []) + len(frag or []) + len(dropped or [])
    except Exception:
        logger.warning("polish-guard flag count crashed (non-fatal); returning 0")
        return 0


# ─────────────────────────────────────────────────────────────────────────────
# V0.5.4 (A1): metadata-wrapper strip helper.
#
# The rendered per-chapter summary carries provenance metadata:
#   - an HTML comment ``<!-- generated-by: ... | started=YYYY-MM-DDTHH:MM:SS ... -->``
#     (invisible in rendered markdown, but parsed by ``extract_dates``
#     as a run timestamp).
#   - a visible footer block
#     ``\\n---\\n\\n*Generated by Elixir v... · run ... · YYYY-MM-DDTHH:MM:SS · N bullets*\\n``
#     (the human-readable stamp).
#   - the COMPLETE sentinel ``<!-- COMPLETE run_id=... -->`` at the end.
#   - (book-level summaries additionally carry a ``> Provider: ... | YYYY-MM-DD``
#     blockquote — included for safety when this helper is reused).
#
# All of these carry RUN dates (the timestamp the summary was generated)
# — NOT source dates. Passing the wrapper to ``extract_dates`` produces
# false-positive "hallucination" + "omission" flags (the
# AUDIT-V0.5.3-ground-truth confirmed 4 of 5 date flags were wrapper- or
# range-component FP).
#
# This helper returns ONLY the summary BODY — the wrapper lines are
# removed. The full ``rendered_md`` is still used for the LLM
# verification + the final output; the stripped body is used ONLY for
# the date-check (where wrapper dates would otherwise cause FP).
# ─────────────────────────────────────────────────────────────────────────────


def _strip_metadata_wrapper(rendered_md: str) -> str:
    """A1 (V0.5.4): strip run-metadata wrapper lines from a rendered
    summary markdown before the deterministic date-check.

    Returns ONLY the summary BODY (the wrapper provenance lines removed).
    Does NOT modify the caller's ``rendered_md`` (returns a new string).
    Fail-open: on any unexpected shape, returns the input unchanged
    (the date-check is advisory-only — never breaks the conversion).
    """
    if not rendered_md:
        return rendered_md
    body = rendered_md
    # Strip the visible footer block: a horizontal rule followed by an
    # italic ``*Generated by Elixir v... · run ... · YYYY-MM-DDTHH:MM:SS · N bullets*``
    # + surrounding blank lines. The rule + italic form is the unique
    # provenance-footer shape; it does not appear in summary bodies.
    body = re.sub(
        r"\n*---\n+\*Generated by[^\n]*\*\s*\n*",
        "\n",
        body,
    )
    # Strip the COMPLETE sentinel (run-id-stamped or legacy bare form).
    body = re.sub(r"\n*<!--\s*COMPLETE[^\n]*-->\s*\n*", "\n", body)
    # Strip the generated-by provenance HTML comment + the trailing
    # blank line that follows it (so the title flows directly into the
    # body's first section).
    body = re.sub(r"<!--\s*generated-by[^\n]*-->\s*\n?", "", body)
    # Strip book-summary "Provider: ... | YYYY-MM-DD" blockquote lines
    # (present only in the assembled book summary; the per-chapter
    # summary never carries this — but this is a content-agnostic
    # helper, so it strips the pattern whenever present).
    body = re.sub(r"^\s*>\s+Provider:[^\n]*\n", "", body, flags=re.MULTILINE)
    return body


