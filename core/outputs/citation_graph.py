"""V10.18.0 (F2): Citation graph generator.

Extracts all academic citations [N] from the markdown text and builds a
graph showing which papers are cited where (chapter, page, context).

Output: a Markdown file with a citation index + a Mermaid graph showing
citation density per chapter.
"""
from __future__ import annotations

import logging
import re
from collections import defaultdict
from collections.abc import Callable
from pathlib import Path
from typing import Any

from core.models import SummaryResult

logger = logging.getLogger(__name__)

_CITATION_RE = re.compile(r'\[(\d+(?:[,\s\-–]+\d+)*)\]')


def generate_citation_graph(
    summaries: list[SummaryResult],
    segments: list[Any],
    raw_markdown: str,
    book_title: str,
    output_dir: Path,
    log_callback: Callable[[str, str], None] | None = None,
) -> Path | None:
    """Generate a citation graph from the book's text + summaries.

    Extracts all [N] citations from:
    - The raw markdown (full text)
    - Each chapter's summary (if available)

    Produces:
    - A citation index (citation # → chapters/pages where it appears)
    - A Mermaid graph showing citation density per chapter
    """
    log = log_callback or (lambda msg, level="INFO": None)

    # Extract citations from raw markdown (grouped by page using page markers)
    citations_by_page: dict[int, set[int]] = defaultdict(set)
    current_page = 1
    for line in raw_markdown.splitlines():
        page_match = re.search(r'<!-- original page (\d+) -->', line)
        if page_match:
            current_page = int(page_match.group(1))
        for match in _CITATION_RE.finditer(line):
            for num_str in re.split(r'[,\s\-–]+', match.group(1)):
                if num_str.isdigit():
                    citations_by_page[current_page].add(int(num_str))

    # Extract citations from summaries (grouped by chapter)
    citations_by_chapter: dict[str, set[int]] = defaultdict(set)
    for s in summaries:
        if not s.success:
            continue
        text = (s.thorough_summary or "") + " " + (s.executive_summary or "")
        for match in _CITATION_RE.finditer(text):
            for num_str in re.split(r'[,\s\-–]+', match.group(1)):
                if num_str.isdigit():
                    citations_by_chapter[s.chapter_heading].add(int(num_str))

    # Build the citation index
    all_citations: set[int] = set()
    for nums in citations_by_page.values():
        all_citations.update(nums)
    for nums in citations_by_chapter.values():
        all_citations.update(nums)

    if not all_citations:
        log("  📊 Citation graph: no citations found in the text.", "INFO")
        return None

    # Build the output
    md_lines = [
        f"# Citation Graph: {book_title}",
        "",
        f"**{len(all_citations)} unique citations found across {len(citations_by_page)} pages.**",
        "",
        "---",
        "",
        "## Citation Index",
        "",
        "| # | Pages | Chapters |",
        "|---|-------|----------|",
    ]

    for cit_num in sorted(all_citations):
        pages = sorted(p for p, nums in citations_by_page.items() if cit_num in nums)
        chapters = [ch for ch, nums in citations_by_chapter.items() if cit_num in nums]
        page_str = ", ".join(str(p) for p in pages[:10])
        if len(pages) > 10:
            page_str += f" (+{len(pages) - 10})"
        chapter_str = "; ".join(ch[:30] for ch in chapters[:3])
        if len(chapters) > 3:
            chapter_str += f" (+{len(chapters) - 3})"
        md_lines.append(f"| [{cit_num}] | {page_str} | {chapter_str} |")

    # Citation density per chapter (Mermaid bar chart)
    md_lines.extend([
        "",
        "---",
        "",
        "## Citation Density by Chapter",
        "",
        "```mermaid",
        "graph LR",
    ])
    for chapter_heading, nums in sorted(citations_by_chapter.items()):
        short = chapter_heading[:20].replace('"', "'")
        md_lines.append(f'    subgraph "{short}"')
        md_lines.append(f'        C{hash(chapter_heading) % 10000}["{len(nums)} citations"]')
        md_lines.append('    end')

    md_lines.extend([
        "```",
        "",
        "---",
        "",
        "*Generated by Elixir V10.18.0*",
    ])

    md_content = "\n".join(md_lines)
    output_path = output_dir / f"{book_title}.Citations.md"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(md_content, encoding="utf-8")
    log(f"  📊 Citation graph: {len(all_citations)} citations → {output_path.name}", "INFO")
    return output_path
